import { GoogleGenAI, Type } from '@google/genai';

export interface AISummaryResult {
  shortSummary: string;
  detailedSummary: string;
  bulletPoints: string[];
  keywords: string[];
}

export interface AIServiceProvider {
  summarizeNote(title: string, content: string, category?: string): Promise<AISummaryResult>;
  explainKeyword(keyword: string, contextTitle?: string): Promise<string>;
}

class GeminiAIService implements AIServiceProvider {
  private getClient(): GoogleGenAI | null {
    const apiKey = process.env.GEMINI_API_KEY;
    if (!apiKey) {
      return null;
    }
    return new GoogleGenAI({
      apiKey,
      httpOptions: {
        headers: {
          'User-Agent': 'aistudio-build',
        },
      },
    });
  }

  async summarizeNote(title: string, content: string, category = 'General'): Promise<AISummaryResult> {
    const ai = this.getClient();

    if (!ai) {
      console.log('GEMINI_API_KEY not configured, falling back to heuristic summary.');
      return this.generateHeuristicSummary(title, content, category);
    }

    try {
      const prompt = `You are TextTutor AI, an expert study assistant and knowledge analyst.
Analyze the following study note and produce a highly structured summary and keyword extraction.

Note Title: "${title}"
Category: "${category}"
Content:
"""
${content}
"""

Instructions:
1. "shortSummary": Provide a crisp, 2-3 sentence overview highlighting the core thesis.
2. "detailedSummary": Provide a comprehensive 2-paragraph deep-dive explaining context, mechanism, and significance.
3. "bulletPoints": Extract 3 to 5 clear, actionable key takeaways or study facts.
4. "keywords": Extract 4 to 8 critical technical concepts or terms suitable for flashcards/study tags.`;

      const response = await ai.models.generateContent({
        model: 'gemini-3.6-flash',
        contents: prompt,
        config: {
          responseMimeType: 'application/json',
          responseSchema: {
            type: Type.OBJECT,
            properties: {
              shortSummary: {
                type: Type.STRING,
                description: 'A crisp 2-3 sentence overview of the note content.',
              },
              detailedSummary: {
                type: Type.STRING,
                description: 'A comprehensive 2-paragraph analysis explaining context and details.',
              },
              bulletPoints: {
                type: Type.ARRAY,
                items: { type: Type.STRING },
                description: '3 to 5 core key takeaways or study points.',
              },
              keywords: {
                type: Type.ARRAY,
                items: { type: Type.STRING },
                description: '4 to 8 essential keywords or technical terms.',
              },
            },
            required: ['shortSummary', 'detailedSummary', 'bulletPoints', 'keywords'],
          },
        },
      });

      if (response.text) {
        const parsed = JSON.parse(response.text.trim());
        return {
          shortSummary: parsed.shortSummary || 'Note summary generated by TextTutor AI.',
          detailedSummary: parsed.detailedSummary || content,
          bulletPoints: Array.isArray(parsed.bulletPoints) && parsed.bulletPoints.length > 0
            ? parsed.bulletPoints
            : ['Core topic analyzed by TextTutor AI.', 'Key formulas and definitions extracted.'],
          keywords: Array.isArray(parsed.keywords) && parsed.keywords.length > 0
            ? parsed.keywords
            : ['note', category.toLowerCase(), 'study'],
        };
      }
    } catch (error) {
      console.error('Error generating AI summary with Gemini:', error);
    }

    return this.generateHeuristicSummary(title, content, category);
  }

  async explainKeyword(keyword: string, contextTitle?: string): Promise<string> {
    const ai = this.getClient();

    if (!ai) {
      return `"${keyword}" is a fundamental term in ${contextTitle || 'this subject'}. It represents a key concept required for comprehensive understanding and study review.`;
    }

    try {
      const prompt = `You are TextTutor AI study tutor.
Provide a clear, easy-to-understand 2-3 sentence explanation of the term "${keyword}"${
        contextTitle ? ` as used in the context of "${contextTitle}"` : ''
      }. Include a practical analogy or core definition.`;

      const response = await ai.models.generateContent({
        model: 'gemini-3.6-flash',
        contents: prompt,
      });

      if (response.text) {
        return response.text.trim();
      }
    } catch (error) {
      console.error('Error generating keyword explanation:', error);
    }

    return `"${keyword}" is a critical concept in ${contextTitle || 'this topic'}. It forms the foundation for understanding related principles and practical applications.`;
  }

  private generateHeuristicSummary(title: string, content: string, category: string): AISummaryResult {
    const sentences = content
      .split(/(?<=[.!?])\s+/)
      .map((s) => s.trim())
      .filter((s) => s.length > 15);

    const words = content
      .toLowerCase()
      .replace(/[^\w\s]/g, '')
      .split(/\s+/)
      .filter((w) => w.length > 4 && !['about', 'there', 'their', 'which', 'where', 'these', 'those', 'other', 'would', 'could'].includes(w));

    const wordCounts: Record<string, number> = {};
    words.forEach((w) => {
      wordCounts[w] = (wordCounts[w] || 0) + 1;
    });

    const topKeywords = Object.entries(wordCounts)
      .sort((a, b) => b[1] - a[1])
      .slice(0, 6)
      .map(([term]) => term);

    if (topKeywords.length === 0) {
      topKeywords.push('concept', category.toLowerCase(), 'study', 'analysis');
    }

    const shortSummary = sentences.length > 0
      ? sentences.slice(0, 2).join(' ')
      : `Summary of "${title}" focusing on key ${category} fundamentals.`;

    const detailedSummary = sentences.length >= 3
      ? `${sentences.slice(0, 2).join(' ')} Furthermore, ${sentences.slice(2, 4).join(' ')}`
      : `${shortSummary} Note contains critical definitions and foundational principles for ${category}.`;

    const bulletPoints = sentences.length > 0
      ? sentences.slice(0, 4).map((s, i) => `${i + 1}. ${s}`)
      : [
          `1. Key concept covered: ${title}.`,
          `2. Category classification: ${category}.`,
          '3. Important formulas and principles indexed for spaced repetition.',
        ];

    return {
      shortSummary,
      detailedSummary,
      bulletPoints,
      keywords: topKeywords,
    };
  }
}

export const aiService = new GeminiAIService();
